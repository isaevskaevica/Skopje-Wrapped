function latin(s) {
  return String(s).replace(/[Ѐ-ӿ]/g, ch => {
    const lo = ch.toLowerCase(), r = TR[lo];
    if (r === undefined) return ch;
    return ch === lo ? r : r.charAt(0).toUpperCase() + r.slice(1);
  });
}
